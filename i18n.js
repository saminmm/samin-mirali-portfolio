  // Retain the original text nodes, spacing and markup (including the hero accent).
  const textBindings = [];
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const nodes = Array.from(element.childNodes).filter(node =>
      node.nodeType === Node.TEXT_NODE && node.textContent.trim()
    );
    element.dataset.i18n.split(/\s+/).forEach((key, index) => {
      const node = nodes[index];
      if (!node) return;
      textBindings.push({
        node, key,
        before: node.textContent.match(/^\s*/)[0],
        after: node.textContent.match(/\s*$/)[0]
      });
    });
  });

  const attributeBindings = [];
  ['alt', 'aria-label', 'content'].forEach(attribute => {
    document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(element => {
      attributeBindings.push({element, attribute,
        key: element.getAttribute(`data-i18n-${attribute}`)});
    });
  });

  let language = 'en';
  try {
    language = supportedLanguage(localStorage.getItem(storageKey));
  } catch {
    // Storage can be disabled; the switch still works for the current page.
  }

  const buttons = document.querySelectorAll('[data-language-toggle]');
  function applyLanguage(nextLanguage) {
    language = supportedLanguage(nextLanguage);
    document.documentElement.lang = language;
    textBindings.forEach(({node, key, before, after}) => {
      const value = translated(key, language);
      if (value !== null) node.textContent = before + value + after;
    });
    attributeBindings.forEach(({element, attribute, key}) => {
      const value = translated(key, language);
      if (value !== null) element.setAttribute(attribute, value);
    });
    buttons.forEach(button => {
      button.textContent = language === 'en' ? 'IT' : 'EN';
      button.setAttribute('aria-label', translated('switchLanguage', language));
      button.title = translated('switchLanguage', language);
      button.hidden = false;
    });
  }

